"""Phase 2: latent-gap study under asynchronous sensor arrival.

For each frame transition src → tgt (= src + k frames) in a dumped scene
we compute trivial baselines for predicting `memory_state_tgt` and report
their L2 gap to the dumped truth. The point of Phase 2 is to size the
slice of the problem that Phase 3's learned speculator actually has to
solve.

## What the speculator actually has to predict

The NEW block `tgt[0 : num_propagated]` has no source counterpart — these
are brand-new query tokens generated by the head from the new camera
image. They are also the only block whose gap to "predict zero" is
non-trivial, and therefore the only block where a learned speculator
can do better than a mechanical copy.

Phase 2 reports both blocks for completeness:
  * CARRIED with "mechanical" baseline — sanity check, expected ~0.
  * NEW with three trivial baselines:
      - zeros           : output 0          (= raw L2 norm of target)
      - copy_prev_new   : output src[0 : num_propagated]   (most similar
                          token distribution; weak content match)
      - copy_prev_mid   : output src[num_propagated : 2·num_propagated]
                          (older tokens, still propagated)

Run:
    python simulate_async.py \
        --dump  ../stages/04_streampetr_latent/dumps/scene_0.pt \
        --out   ../stages/04_streampetr_latent/dumps/phase2_gaps.npz \
        --max-k 3
"""

import argparse
import os
import sys
from dataclasses import dataclass

import numpy as np
import torch

_HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, _HERE)

NUM_PROPAGATED = 256        # head's num_propagated (new tokens per frame)
MEMORY_LEN = 1024           # head's memory_len (carried tokens per frame)
M_TOTAL = NUM_PROPAGATED + MEMORY_LEN


@dataclass
class FrameTuple:
    """Convenience view of one dumped frame."""
    sample_token: str
    timestamp: float
    ego_pose: np.ndarray                    # [4, 4]
    memory_embedding: torch.Tensor          # [M, D]
    memory_reference_point: torch.Tensor    # [M, 3]  in global frame
    memory_timestamp: torch.Tensor          # [M, 1]
    memory_egopose: torch.Tensor            # [M, 4, 4]
    memory_velo: torch.Tensor               # [M, 2]


def _load_frames(dump_path: str):
    dump = torch.load(dump_path, map_location="cpu", weights_only=False)
    scene_tok = list(dump.keys())[0]
    raw = dump[scene_tok]["frames"]
    frames = [
        FrameTuple(
            sample_token=f["sample_token"],
            timestamp=f["timestamp"],
            ego_pose=f["ego_pose"],
            memory_embedding=f["memory_embedding"],
            memory_reference_point=f["memory_reference_point"],
            memory_timestamp=f["memory_timestamp"],
            memory_egopose=f["memory_egopose"],
            memory_velo=f["memory_velo"],
        )
        for f in raw
    ]
    return scene_tok, frames


# ---------------------------------------------------------------------------
# Metric
# ---------------------------------------------------------------------------
def _l2_stats(pred: torch.Tensor, target: torch.Tensor) -> dict:
    """Per-token L2 norm over the last dim, then aggregate over tokens."""
    assert pred.shape == target.shape, (pred.shape, target.shape)
    diff = (pred - target).float()
    l2 = diff.norm(dim=-1)
    return {
        "mean":   float(l2.mean()),
        "median": float(l2.median()),
        "p90":    float(l2.quantile(0.9)),
        "max":    float(l2.max()),
        "n":      int(l2.numel()),
    }


# ---------------------------------------------------------------------------
# Per-pair evaluation. Each "row" is (block, baseline) → stats dict.
# ---------------------------------------------------------------------------
def _embedding_rows(src: FrameTuple, tgt: FrameTuple, k: int) -> dict:
    """Embedding L2 gaps for each (block, baseline).

    For a k-step transition, the mechanical correspondence is
        tgt[k·NUM_PROPAGATED + i]  ==  src[i]
    for i in [0, M_TOTAL - k·NUM_PROPAGATED), because each of the k
    intermediate forward passes prepended NUM_PROPAGATED new tokens and
    trimmed the tail. The "carried" block therefore shrinks as k grows;
    at k=5 it would vanish. If it's empty we drop the row.
    """
    src_emb = src.memory_embedding
    tgt_emb = tgt.memory_embedding
    shift = k * NUM_PROPAGATED
    carried_len = M_TOTAL - shift                                 # may be ≤ 0
    rows = {}

    if carried_len > 0:
        rows[("carried", "mechanical")] = _l2_stats(
            pred=src_emb[:carried_len],
            target=tgt_emb[shift : shift + carried_len],
        )

    # NEW block at tgt — always slots [0, NUM_PROPAGATED).
    tgt_new = tgt_emb[:NUM_PROPAGATED]                            # [256, D]
    rows[("new", "zeros")] = _l2_stats(
        pred=torch.zeros_like(tgt_new), target=tgt_new,
    )
    rows[("new", "copy_prev_new")] = _l2_stats(
        pred=src_emb[:NUM_PROPAGATED], target=tgt_new,
    )
    rows[("new", "copy_prev_mid")] = _l2_stats(
        pred=src_emb[NUM_PROPAGATED : 2 * NUM_PROPAGATED],
        target=tgt_new,
    )
    return rows


def _refpoint_rows(src: FrameTuple, tgt: FrameTuple, dt: float, k: int) -> dict:
    """Reference-point L2 gaps. Ref points are in GLOBAL frame in dumps.

    Same k-step correspondence as the embedding rows. Velocity baseline
    only applies to the NEW block — for the carried block, ref points are
    stored frozen in global, so the head doesn't roll them.
    """
    src_ref = src.memory_reference_point
    src_velo = src.memory_velo
    tgt_ref = tgt.memory_reference_point
    shift = k * NUM_PROPAGATED
    carried_len = M_TOTAL - shift
    rows = {}

    if carried_len > 0:
        rows[("carried", "mechanical")] = _l2_stats(
            pred=src_ref[:carried_len],
            target=tgt_ref[shift : shift + carried_len],
        )

    tgt_new = tgt_ref[:NUM_PROPAGATED]                            # [256, 3]
    rows[("new", "zeros")] = _l2_stats(
        pred=torch.zeros_like(tgt_new), target=tgt_new,
    )
    rows[("new", "copy_prev_new")] = _l2_stats(
        pred=src_ref[:NUM_PROPAGATED], target=tgt_new,
    )
    rows[("new", "copy_prev_new_velo")] = _l2_stats(
        pred=torch.cat([
            src_ref[:NUM_PROPAGATED, :2]
                + src_velo[:NUM_PROPAGATED] * dt,
            src_ref[:NUM_PROPAGATED, 2:],
        ], dim=-1),
        target=tgt_new,
    )
    return rows


def evaluate_pair(src: FrameTuple, tgt: FrameTuple, k: int) -> dict:
    dt = tgt.timestamp - src.timestamp
    return {
        "k": k,
        "dt": dt,
        "embedding": _embedding_rows(src, tgt, k),
        "refpoint":  _refpoint_rows(src, tgt, dt, k),
    }


# ---------------------------------------------------------------------------
# Aggregation across pairs, grouped by k.
# ---------------------------------------------------------------------------
def aggregate_by_k(per_pair: list, max_k: int) -> dict:
    by_k = {k: [] for k in range(1, max_k + 1)}
    for rec in per_pair:
        if rec["k"] in by_k:
            by_k[rec["k"]].append(rec)

    summary = {}
    for k, recs in by_k.items():
        if not recs:
            continue
        agg = {"n_pairs": len(recs), "dt_mean": float(np.mean([r["dt"] for r in recs]))}
        for kind in ("embedding", "refpoint"):
            agg[kind] = {}
            rows0 = recs[0][kind].keys()
            for row in rows0:
                stats = {}
                for stat in ("mean", "median", "p90", "max"):
                    stats[stat] = float(np.mean([r[kind][row][stat] for r in recs]))
                agg[kind][row] = stats
        summary[k] = agg
    return summary


def print_summary(summary: dict):
    print("\nPer-k baseline gaps (averaged over scene's frame pairs)")
    print("=" * 80)
    for k in sorted(summary):
        agg = summary[k]
        print(f"\nk = {k}  (predict {k} frame(s) ahead, {agg['n_pairs']} pairs, "
              f"dt≈{agg['dt_mean']:.2f}s)")
        for kind in ("embedding", "refpoint"):
            print(f"  {kind}:")
            for (block, bl), stats in agg[kind].items():
                tag = f"{block:8s} / {bl:20s}"
                print(f"    {tag}  mean={stats['mean']:9.4f}  "
                      f"median={stats['median']:9.4f}  "
                      f"p90={stats['p90']:9.4f}  "
                      f"max={stats['max']:9.4f}")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--dump", required=True,
                    help=".pt produced by dump_latents.py")
    ap.add_argument("--out", default=None,
                    help="optional .npz to save the summary into")
    ap.add_argument("--max-k", type=int, default=3,
                    help="evaluate predictions up to k frames ahead")
    args = ap.parse_args()

    scene_tok, frames = _load_frames(args.dump)
    T = len(frames)
    print(f"Scene {scene_tok[:8]}: {T} frames")

    per_pair = []
    for f0 in range(T):
        for k in range(1, args.max_k + 1):
            f1 = f0 + k
            if f1 >= T:
                continue
            per_pair.append(evaluate_pair(frames[f0], frames[f1], k))

    summary = aggregate_by_k(per_pair, max_k=args.max_k)
    print_summary(summary)

    if args.out:
        os.makedirs(os.path.dirname(args.out) or ".", exist_ok=True)
        flat = {}
        for k, agg in summary.items():
            for kind in ("embedding", "refpoint"):
                for (block, bl), stats in agg[kind].items():
                    for stat, val in stats.items():
                        flat[f"k{k}_{kind}_{block}_{bl}_{stat}"] = float(val)
        np.savez(args.out, **flat)
        print(f"\nSaved summary → {args.out}")


if __name__ == "__main__":
    main()
